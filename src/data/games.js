export const getGameBySlug = (slug) => games.find((g) => g.slug === slug)
export const getSimilarGames = (currentSlug, genre, limit = 4) => {
  const others = games.filter((g) => g.slug !== currentSlug)
  const sameGenre = others.filter(
    (g) =>
      g.genre.toLowerCase() === genre.toLowerCase() ||
      (g.genres && g.genres.some((gn) => gn.toLowerCase() === genre.toLowerCase())),
  )
  if (sameGenre.length >= limit) {
    return sameGenre.slice(0, limit)
  }
  const remaining = others.filter((g) => !sameGenre.some((sg) => sg.id === g.id))
  return [...sameGenre, ...remaining].slice(0, limit)
}
